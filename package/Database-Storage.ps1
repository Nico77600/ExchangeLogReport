    The storage options: --storage-audit, --storage-copy, --database, --destination, --output, --confirm-copy,
    --migrate, --repack, --vacuum, --sqlite-tool.

.NOTES
    Author  : Nicolas Fabert
    Version : 3.1.0
    Exit codes : 0 = done, 2 = refused or failed (the message is on the error stream and in the JSON on stdout).

    This Script is a Personal project.
    It's provided "AS-IS". It's not an official Microsoft product so no support can be expected from Microsoft.

    As any scripts you must read carefully the documentation and test it first in a Test environment before any run in Production.
#>

<#
.SYNOPSIS
    Database storage maintenance: a read-only audit of what takes space, or a new compacted, migrated or repacked copy.

.DESCRIPTION
    Runs the storage commands of the Exchange Log Report package in the bundled PowerShell (Database-Storage.cmd
    starts it). The source database is never changed: a copy is written to a new file and verified. Without argument
    the three usual commands are printed. The engine and the storage sources (src\Engine.*.cs, src\Storage.*.cs)
    are compiled in memory at start; the start takes a few seconds.

